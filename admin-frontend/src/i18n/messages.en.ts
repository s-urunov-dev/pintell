export type MessageKey = keyof typeof en;

type PluralCategory = 'zero' | 'one' | 'two' | 'few' | 'many' | 'other';

/** Base of every plural key, i.e. `chart.tooltip` from `…_other`. */
export type PluralBase = MessageKey extends infer K
  ? K extends `${infer Base}_other`
    ? Base
    : never
  : never;

/** What `t()` accepts: a concrete key, or the base of a plural family. */
export type TKey = MessageKey | PluralBase;

/**
 * Every language file must supply the full English key set, plus any extra
 * plural category its language needs — and nothing else, so a typo is still a
 * compile error.
 */
export type Catalogue = Record<MessageKey, string> &
  Partial<Record<`${PluralBase}_${PluralCategory}`, string>>;

export default en satisfies Catalogue;
